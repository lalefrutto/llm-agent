"""
guardrails.py — детерминированные проверки поверх решений LLM.

Зачем: живой прогон показал, что 8B-роутер на запрос «Удали все файлы в моей
рабочей директории» трижды делегировал executor'у и только на 4-м шаге
вернул ask_user (кейс t03 этого не ловил — он смотрит лишь на первое
решение, а оно недетерминировано при temperature 0.2). Правило из
промпта — первая линия защиты, этот модуль — вторая, которую модель
обойти не может:

1. Необратимый запрос пользователя -> граф сам отвечает ask_user, не
   спрашивая LLM, и запоминает действие как ожидающее подтверждения.
2. Следующее сообщение-подтверждение («да, подтверждаю») в том же треде
   снимает блокировку ровно для этого действия.
3. Разрушающий код (os.remove, shutil.rmtree, ...) в code_exec
   блокируется, пока действие не подтверждено.
"""
from __future__ import annotations

import re

# Намерение пользователя совершить необратимое действие. Глагол + объект,
# чтобы не мешать обычной обработке данных: «удали дубликаты» или «очисти
# от выбросов» — это работа с датафреймом в памяти, а не с файлами.
_OBJECTS = r"(файл|папк|директор|каталог|\bвсё\b|\bвсе\b|баз|таблиц|запис|репозитори|аккаунт|workspace)"
_IRREVERSIBLE = [
    (r"\b(удал(и|ить|ите|яй|ять)|сотр(и|ите)|стереть|очист(и|ить|ите))\b.*" + _OBJECTS, "удаление данных"),
    (r"\bперезапиш(и|ите)\b.*" + _OBJECTS, "перезапись файлов"),
    (r"\brm\s+-rf?\b|\bdrop\s+table\b|\btruncate\s+table\b", "удаление данных"),
    (r"\bотправ(ь|ить|ьте)\b.*\b(письм|сообщени|email|e-mail)", "отправка сообщения от имени пользователя"),
    (r"\b(оплат(и|ить)|переведи|перевести)\b.*\b(деньг|руб|\$|€|оплат|счёт|счет|карт)", "финансовая операция"),
]

_CONFIRM = re.compile(
    r"^\s*(да|ага|yes|подтверждаю|подтверждаю удаление|выполняй|делай|давай)\b[\s,.!]*"
    r"(подтверждаю|выполняй|удаляй|делай|давай)?[\s.!]*$", re.IGNORECASE)

# Разрушающие операции в коде для sandbox. Отдельно от сетевого фильтра
# code_exec._BLOCKED_SUBSTRINGS: те блокируются всегда, эти — только без
# подтверждения пользователя.
DESTRUCTIVE_CODE = (
    "os.remove", "os.unlink", "os.rmdir", "os.removedirs", "shutil.rmtree",
    ".unlink(", ".rmdir(", "rm -rf", "rm -r ", "truncate(",
)


def irreversible_reason(text: str) -> str | None:
    """Причина, если сообщение просит необратимое действие, иначе None."""
    lowered = text.lower()
    for pattern, reason in _IRREVERSIBLE:
        if re.search(pattern, lowered):
            return reason
    return None


def is_confirmation(text: str) -> bool:
    return bool(_CONFIRM.match(text.strip()))


def destructive_pattern(code: str) -> str | None:
    for p in DESTRUCTIVE_CODE:
        if p in code:
            return p
    return None
